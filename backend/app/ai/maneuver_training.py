import csv
from datetime import datetime, timezone
import hashlib
import json
import math
from pathlib import Path
import random
import time

import numpy as np

from app.ai.maneuver_ranker import (
    ARTIFACT_DIR, ARTIFACT_PATH, FEATURES, FEATURE_SCHEMA_VERSION,
    METADATA_PATH, MODEL_NAME, MODEL_VERSION, feature_vector,
)
from app.models import ConjunctionAssessmentEvent, ObjectSummary, PhysicsResult, Provenance, ScientificField
from app.services.conjunction import optimize_maneuver


BACKEND = Path(__file__).resolve().parents[2]
DATA_PATH = BACKEND / "ml_data" / "maneuver_rank_synthetic_v1.csv"
SEED = 1501
GENERATOR_VERSION = "1.0.0"
MAGNITUDES = (0.005, 0.02, 0.05)


def _scenario(index: int, rng: random.Random) -> ConjunctionAssessmentEvent:
    """Create varied synthetic TCA states for offline simulator experiments."""
    epoch = "2026-01-01T00:00:00+00:00"
    primary_id, secondary_id = f"SYN-{index:04d}-A", f"SYN-{index:04d}-B"
    p = Provenance(
        source="deterministic synthetic two-body training scenario",
        source_type="synthetic", reference_frame="TEME", is_synthetic=True,
        method="seeded synthetic Cartesian TCA generator", method_version=GENERATOR_VERSION,
        validity_status="valid",
    )
    angle = rng.uniform(-math.pi, math.pi)
    radius = rng.uniform(6800.0, 7400.0)
    speed = math.sqrt(398600.4418 / radius) * rng.uniform(0.998, 1.002)
    pos = np.asarray([radius * math.cos(angle), radius * math.sin(angle), rng.uniform(-80, 80)])
    tangential = np.asarray([-math.sin(angle), math.cos(angle), 0.0])
    vel = speed * tangential + np.asarray([0.0, 0.0, rng.uniform(-0.08, 0.08)])
    separation = rng.uniform(0.1, 20.0)
    rel = np.asarray([rng.uniform(-1, 1), rng.uniform(-1, 1), rng.uniform(-1, 1)])
    rel *= separation / np.linalg.norm(rel)
    axis = np.asarray([0.0, 0.0, 1.0]) if abs(rel[2]) < 0.8 * separation else np.asarray([0.0, 1.0, 0.0])
    cross = np.cross(rel, axis)
    cross /= np.linalg.norm(cross)
    rel_speed = rng.uniform(0.001, 0.02)
    rel_vel = cross * rel_speed
    secondary_pos, secondary_vel = pos + rel, vel + rel_vel

    primary = ObjectSummary(
        id=primary_id, name=primary_id, category="active", object_type="ACTIVE_SATELLITE",
        band="LEO", orbit_type="LEO", altitude_km=float(radius - 6378.137),
        inclination_deg=0.0, velocity_kms=float(np.linalg.norm(vel)),
        heuristic_risk_score=0.0, heuristic_forecast_score=0.0,
        provenance=p, heuristic_score_provenance=p,
    )
    secondary = ObjectSummary(
        id=secondary_id, name=secondary_id, category="debris", object_type="SPACE_DEBRIS",
        band="LEO", orbit_type="LEO", altitude_km=float(np.linalg.norm(secondary_pos) - 6378.137),
        inclination_deg=0.0, velocity_kms=float(np.linalg.norm(secondary_vel)),
        heuristic_risk_score=0.0, heuristic_forecast_score=0.0,
        provenance=p, heuristic_score_provenance=p,
    )
    event_id = f"SYN-SCENARIO-{index:04d}"
    state1 = {"object_id": primary_id, "epoch": epoch, "position_km": pos.tolist(), "velocity_km_s": vel.tolist(), "frame": "TEME"}
    state2 = {"object_id": secondary_id, "epoch": epoch, "position_km": secondary_pos.tolist(), "velocity_km_s": secondary_vel.tolist(), "frame": "TEME"}
    physics = PhysicsResult(
        event_id=event_id, status="valid", applicability="synthetic_training_scenario", provenance=p,
        object_primary_id=primary_id, object_secondary_id=secondary_id,
        state_information={"source_frame": "TEME", "target_frame": "TEME", "position_units": "km", "velocity_units": "km/s"},
        tca_status="valid", tca=ScientificField(status="available", value=epoch, units="UTC"),
        miss_distance=ScientificField(status="available", value=float(np.linalg.norm(rel)), units="km"),
        primary_state_at_tca=state1, secondary_state_at_tca=state2,
    )
    return ConjunctionAssessmentEvent(
        id=event_id, primary=primary, secondary=secondary, obj_a=primary, obj_b=secondary,
        pair_type="synthetic active/debris", provenance=p, physics_result=physics,
    )


def _rank_statistics(rows: list[dict], estimator) -> dict:
    from scipy.stats import spearmanr
    y = np.asarray([row["target_miss_distance_km"] for row in rows], dtype=float)
    x = np.asarray([row["features"] for row in rows], dtype=float)
    pred = np.asarray(estimator.predict(x), dtype=float)
    errors = pred - y
    by_scenario: dict[str, list[int]] = {}
    for i, row in enumerate(rows):
        by_scenario.setdefault(row["scenario_id"], []).append(i)
    top1, regret, base_regret, group_ranks = [], [], [], []
    for indexes in by_scenario.values():
        actual = y[indexes]
        estimated = pred[indexes]
        selected = int(np.argmin(estimated))
        oracle = int(np.argmin(actual))
        conservative = int(np.argmin([rows[index]["delta_v_m_s"] for index in indexes]))
        top1.append(selected == oracle)
        regret.append(float(actual[selected] - actual[oracle]))
        base_regret.append(float(actual[conservative] - actual[oracle]))
        rank = spearmanr(actual, estimated).statistic
        if math.isfinite(float(rank)):
            group_ranks.append(float(rank))
    return {
        "candidate_count": len(rows),
        "scenario_count": len(by_scenario),
        "mae_km": float(np.mean(np.abs(errors))),
        "rmse_km": float(np.sqrt(np.mean(errors ** 2))),
        "r2": float(1 - np.sum(errors ** 2) / np.sum((y - y.mean()) ** 2)) if np.ptp(y) else None,
        "candidate_level_spearman": float(spearmanr(y, pred).statistic) if np.ptp(y) and np.ptp(pred) else None,
        "mean_within_scenario_spearman": float(np.mean(group_ranks)) if group_ranks else None,
        "top1_agreement_with_simulator_best": float(np.mean(top1)),
        "mean_selected_simulator_miss_regret_vs_best_km": float(np.mean(regret)),
        "minimum_delta_v_baseline_mean_regret_vs_best_km": float(np.mean(base_regret)),
    }


def train_and_evaluate(scenario_count: int = 60) -> dict:
    if isinstance(scenario_count, bool) or not isinstance(scenario_count, int) or not 30 <= scenario_count <= 100:
        raise ValueError("scenario_count must be an integer from 30 through 100")
    try:
        import joblib
        import sklearn
        from sklearn.ensemble import RandomForestRegressor
    except ImportError as exc:
        raise RuntimeError("The existing scikit-learn/joblib runtime is required; no installation was attempted") from exc
    started = time.perf_counter()
    rng = random.Random(SEED)
    rows: list[dict] = []
    boundary_candidate_count = 0
    scenario_ids = [f"SYN-SCENARIO-{i:04d}" for i in range(scenario_count)]
    leads = (60.0, 300.0, 900.0, 1800.0)
    for index, scenario_id in enumerate(scenario_ids):
        event = _scenario(index, rng)
        lead = leads[index % len(leads)]
        magnitude = MAGNITUDES[index % len(MAGNITUDES)]
        result = optimize_maneuver(event, lead_seconds=lead, burn_magnitudes_m_s=(magnitude,))
        if result.get("physics_candidate_status") != "evaluated":
            raise RuntimeError(f"Synthetic scenario {scenario_id} did not produce physics outcomes: {result.get('reason_code')}")
        for candidate in result["candidates"]:
            if candidate["objective_status"] == "search_boundary_minimum":
                boundary_candidate_count += 1
                continue
            if candidate["delta_v_m_s"] == 0:
                continue
            rows.append({
                "scenario_id": scenario_id,
                "event_id": event.id,
                "lead_time_seconds": lead,
                "delta_v_m_s": float(candidate["delta_v_m_s"]),
                "features": feature_vector(event, candidate, lead),
                "target_miss_distance_km": float(candidate["predicted_miss_distance_km"]),
                "direction": candidate["direction"],
                "objective_status": candidate["objective_status"],
            })
    split_ids = sorted(scenario_ids)
    random.Random(SEED).shuffle(split_ids)
    train_end, val_end = int(0.60 * scenario_count), int(0.80 * scenario_count)
    scenario_splits = {
        "train": set(split_ids[:train_end]),
        "validation": set(split_ids[train_end:val_end]),
        "test": set(split_ids[val_end:]),
    }
    if any(scenario_splits[a] & scenario_splits[b] for a, b in (("train", "validation"), ("train", "test"), ("validation", "test"))):
        raise AssertionError("Scenario leakage detected")
    train_rows = [row for row in rows if row["scenario_id"] in scenario_splits["train"]]
    test_rows = [row for row in rows if row["scenario_id"] in scenario_splits["test"]]
    estimator = RandomForestRegressor(n_estimators=160, max_depth=12, min_samples_leaf=2, max_features=1.0, random_state=SEED, n_jobs=1)
    estimator.fit(np.asarray([row["features"] for row in train_rows]), np.asarray([row["target_miss_distance_km"] for row in train_rows]))
    test_metrics = _rank_statistics(test_rows, estimator)
    baseline_metrics = _minimum_dv_baseline(test_rows)

    DATA_PATH.parent.mkdir(parents=True, exist_ok=True)
    with DATA_PATH.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["scenario_id", "event_id", "lead_time_seconds", "delta_v_m_s", "direction", *FEATURES, "target_miss_distance_km", "objective_status", "label_provenance"])
        for row in rows:
            writer.writerow([row["scenario_id"], row["event_id"], row["lead_time_seconds"], row["delta_v_m_s"], row["direction"], *row["features"], row["target_miss_distance_km"], row["objective_status"], "existing optimize_maneuver two-body simulation; synthetic scenario"])
    dataset_sha = _sha256(DATA_PATH)
    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    bundle = {"estimator": estimator, "feature_names": list(FEATURES), "feature_schema_version": FEATURE_SCHEMA_VERSION, "model_name": MODEL_NAME, "model_version": MODEL_VERSION}
    joblib.dump(bundle, ARTIFACT_PATH, compress=3)
    metadata = {
        "model_name": MODEL_NAME, "model_version": MODEL_VERSION,
        "artifact_filename": ARTIFACT_PATH.name, "artifact_sha256": _sha256(ARTIFACT_PATH),
        "metadata_path": str(METADATA_PATH.relative_to(BACKEND)),
        "feature_schema_version": FEATURE_SCHEMA_VERSION, "feature_names": list(FEATURES),
        "features": {name: _feature_description(name) for name in FEATURES},
        "target": "existing simulator candidate predicted_miss_distance_km",
        "target_units": "km",
        "target_semantics": "Closest-approach distance from the bounded Earth two-body point-mass RK4 simulator; lower values are ranked earlier. This is a simulator surrogate, not a real-world outcome, Pc, safety score, or optimizer improvement claim.",
        "dataset_filename": DATA_PATH.name, "dataset_sha256": dataset_sha,
        "dataset_provenance": "Deterministic synthetic Cartesian encounter scenarios generated by app.ai.maneuver_training._scenario with seed 1501; every target is computed by the existing app.services.conjunction.optimize_maneuver implementation.",
        "scenario_generation_assumptions": ["TCA Cartesian states are synthetic TEME-labelled inputs with primary radius 6800-7400 km, near-circular primary speed within 0.2% of the configured two-body circular speed, relative separation 0.1-20 km, and orthogonal relative speed 0.001-0.02 km/s.", "Burn leads cycle through 60, 300, 900, and 1800 seconds.", "Each scenario cycles one candidate magnitude (0.005, 0.02, or 0.05 m/s); simulator labels six RTN directions plus a zero-burn baseline, which is excluded from candidate model training.", "Labels use the current two-body RK4 simulator and its bounded closest-approach search; simulation limitations are inherited."],
        "scenario_counts": {name: len(ids) for name, ids in scenario_splits.items()},
        "candidate_row_counts": {name: sum(row["scenario_id"] in ids for row in rows) for name, ids in scenario_splits.items()},
        "boundary_candidates_excluded_from_training_and_evaluation": boundary_candidate_count,
        "scenario_split_hashes_sha256": {name: hashlib.sha256("\n".join(sorted(ids)).encode()).hexdigest() for name, ids in scenario_splits.items()},
        "split_protocol": "60/20/20 deterministic split by independent scenario_id; all candidate rows from a scenario remain in one partition.",
        "estimator": "RandomForestRegressor(n_estimators=160, max_depth=12, min_samples_leaf=2, max_features=1.0, random_state=1501, n_jobs=1)",
        "training_candidate_rows": len(train_rows), "test_metrics": test_metrics,
        "baseline": {"name": "minimum delta-v candidate; deterministic generation order breaks ties", "test_metrics": baseline_metrics},
        "scikit_learn_version": sklearn.__version__,
        "limitations": ["All training/evaluation scenarios and target labels are synthetic simulator outputs; no real maneuver outcomes were available or used.", "The model approximates one specific bounded two-body simulator; it does not discover superior maneuvers and cannot validate the simulator.", "No covariance, Pc, spacecraft control, execution error, attitude, propulsion, J2, drag, third-body effects, or operational constraints are modeled.", "The simulator's comparison against the stored SGP4 encounter is diagnostic only; neither the model score nor physical miss distance establishes a safe or effective maneuver."],
        "training_elapsed_seconds": round(time.perf_counter() - started, 3),
    }
    METADATA_PATH.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    return metadata


def _minimum_dv_baseline(rows: list[dict]) -> dict:
    by_scenario: dict[str, list[dict]] = {}
    for row in rows:
        by_scenario.setdefault(row["scenario_id"], []).append(row)
    regrets = []
    for candidates in by_scenario.values():
        best = min(row["target_miss_distance_km"] for row in candidates)
        selected = min(candidates, key=lambda row: row["delta_v_m_s"])
        regrets.append(selected["target_miss_distance_km"] - best)
    return {"scenario_count": len(by_scenario), "mean_selected_simulator_miss_regret_vs_best_km": float(np.mean(regrets)) if regrets else None}


def _feature_description(name: str) -> dict[str, str]:
    if name.endswith("_km_s"):
        return {"units": "km/s", "frame_epoch": "TEME at TCA"}
    if name.endswith("_km"):
        return {"units": "km", "frame_epoch": "TEME at TCA"}
    if name == "delta_v_m_s":
        return {"units": "m/s", "frame_epoch": "burn magnitude; direction is a separate RTN category"}
    if name == "lead_time_seconds":
        return {"units": "s", "frame_epoch": "TCA minus burn epoch"}
    return {"units": "unitless one-hot", "frame_epoch": "RTN direction label generated by existing simulator at burn epoch"}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


if __name__ == "__main__":
    print(json.dumps(train_and_evaluate(), indent=2))

