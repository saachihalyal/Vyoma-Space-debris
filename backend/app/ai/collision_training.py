"""Offline scenario generation and training for the two collision AI models.

Run from ``backend`` with ``python -m app.ai.collision_training``. Every label
is generated by the ORION research Pc estimator from a real archived CelesTrak
screening event, and all variants from a parent event remain in one split.
"""

