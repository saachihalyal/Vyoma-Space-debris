import json
from pathlib import Path
import random
from typing import Any

import numpy as np

from app.ai.collision_features import FEATURE_NAMES, FEATURE_SCHEMA_VERSION, FEATURE_UNITS, build_collision_features
from app.models import ConjunctionAssessmentEvent
from app.services.automatic_research_pc import METHOD_VERSION, assess_automatic_research_pc
from app.services.probability_classification import ORION_RISK_POLICY_VERSION


SEED = 20261024
MODEL_VERSION = "1.0.0"
SCENARIO_DATASET_VERSION = "orion-collision-scenarios-v1"
SNAPSHOT_JOB_ID = "08c33d64c8d34ddfb6838a565d3c0db3"
BACKEND_DIR = Path(__file__).resolve().parents[2]
SNAPSHOT_PATH = BACKEND_DIR / "exports" / f"screening-job-{SNAPSHOT_JOB_ID}.json"
DATASET_PATH = BACKEND_DIR / "ml_data" / f"{SCENARIO_DATASET_VERSION}.jsonl"
SPLIT_PATH = BACKEND_DIR / "ml_data" / f"{SCENARIO_DATASET_VERSION}-splits.json"
ARTIFACT_DIR = Path(__file__).resolve().parent / "artifacts"
PC_ARTIFACT = ARTIFACT_DIR / "orion_research_pc_surrogate.joblib"
PC_METADATA = ARTIFACT_DIR / "orion_research_pc_surrogate.metadata.json"
RISK_ARTIFACT = ARTIFACT_DIR / "orion_physics_risk_classifier.joblib"
RISK_METADATA = ARTIFACT_DIR / "orion_physics_risk_classifier.metadata.json"
COVARIANCE_SCALES = (0.5, 1.0, 2.0, 3.0)
HBR_SCALES = (0.75, 1.0, 1.5)
RISK_CLASSES = ("Low", "Medium", "High")
PC_TARGET_DEFINITION = "log10(research_pc), generated by ORION Foster 2D using the ESA population-prior covariance and assumed HBR model"
RISK_TARGET_DEFINITION = "Low/Medium/High labels from the same generated research_pc under orion-physics-pc-risk-v1"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_parent_events(snapshot_path: Path = SNAPSHOT_PATH) -> tuple[dict[str, Any], list[ConjunctionAssessmentEvent]]:
    snapshot = json.loads(snapshot_path.read_text(encoding="utf-8"))
    if snapshot.get("job_id") != SNAPSHOT_JOB_ID:
        raise ValueError(f"Expected saved CelesTrak snapshot {SNAPSHOT_JOB_ID}; found {snapshot.get('job_id')!r}")
    events = []
    for record in snapshot.get("result", {}).get("data", []):
        if record.get("physics_result", {}).get("status") != "valid":
            continue
        try:
            event = ConjunctionAssessmentEvent.model_validate(record)
        except Exception:
            continue
        if not _has_real_celestrak_inputs(event):
            continue
        events.append(event)
    if not events:
        raise ValueError("The saved screening snapshot has no valid, non-synthetic CelesTrak events")
    return snapshot, events


def _has_real_celestrak_inputs(event: ConjunctionAssessmentEvent) -> bool:
    """Require two independently sourced, real CelesTrak object records.

    The conjunction itself has ``derived`` provenance because it is calculated
    from its parent catalog records; that does not make its input observations
    synthetic. Both object records must retain their original live source URL.
    """
    if event.provenance.is_synthetic or event.provenance.source_type not in {"live", "derived"}:
        return False
    for obj in (event.primary, event.secondary):
        provenance = obj.provenance
        if provenance is None:
            return False
        source = str(getattr(provenance, "source", "")).lower()
        source_type = getattr(provenance, "source_type", None)
        source_record = getattr(provenance, "source_record", None) or {}
        source_url = str(source_record.get("source_url", "")).lower() if isinstance(source_record, dict) else ""
        if (source_type != "live" or getattr(provenance, "is_synthetic", True)
                or "celestrak" not in source or not source_url.startswith("https://celestrak.org/")):
            return False
    return True


def generate_scenarios(snapshot_path: Path = SNAPSHOT_PATH) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    snapshot, events = read_parent_events(snapshot_path)
    scenarios: list[dict[str, Any]] = []
    rejected: dict[str, int] = {}
    for event in events:
        for covariance_scale in COVARIANCE_SCALES:
            for hbr_scale in HBR_SCALES:
                assessment = assess_automatic_research_pc(
                    event.physics_result, event.collision_probability, event.review_priority,
                    primary=event.primary, secondary=event.secondary,
                    covariance_scale=covariance_scale, hbr_scale=hbr_scale,
                )
                if assessment.status != "prior_based_research_estimate" or assessment.risk_assessment is None:
                    reason = assessment.reason_codes[0] if assessment.reason_codes else assessment.status
                    rejected[reason] = rejected.get(reason, 0) + 1
                    continue
                if assessment.risk_assessment.status != "classified":
                    rejected[assessment.risk_assessment.reason_code or "RISK_CLASSIFICATION_UNAVAILABLE"] = rejected.get(
                        assessment.risk_assessment.reason_code or "RISK_CLASSIFICATION_UNAVAILABLE", 0,
                    ) + 1
                    continue
                feature_values = build_collision_features(event, assessment)
                if feature_values is None:
                    rejected["LIVE_FEATURES_UNAVAILABLE"] = rejected.get("LIVE_FEATURES_UNAVAILABLE", 0) + 1
                    continue
                try:
                    target_log10_pc = float(Decimal(assessment.estimated_pc_scientific).log10())
                except (InvalidOperation, TypeError, ValueError) as exc:
                    rejected["RESEARCH_PC_LOG_TARGET_INVALID"] = rejected.get("RESEARCH_PC_LOG_TARGET_INVALID", 0) + 1
                    continue
                if not math_isfinite(target_log10_pc) or target_log10_pc > 0:
                    rejected["RESEARCH_PC_LOG_TARGET_OUT_OF_RANGE"] = rejected.get("RESEARCH_PC_LOG_TARGET_OUT_OF_RANGE", 0) + 1
                    continue
                scenarios.append({
                    "parent_event_id": event.id,
                    "scenario_id": f"{event.id}|cov={covariance_scale:g}|hbr={hbr_scale:g}",
                    "original_event_provenance": {
                        "conjunction_source_type": event.provenance.source_type,
                        "conjunction_source": event.provenance.source,
                        "object_inputs": [
                            {
                                "object_id": obj.id,
                                "source_type": obj.provenance.source_type,
                                "source": obj.provenance.source,
                                "source_timestamp": obj.provenance.source_timestamp,
                                "element_epoch": obj.provenance.element_epoch,
                                "input_hash": obj.provenance.input_hash,
                                "source_url": (obj.provenance.source_record or {}).get("source_url"),
                                "source_group": (obj.provenance.source_record or {}).get("source_group"),
                                "is_synthetic": obj.provenance.is_synthetic,
                            }
                            for obj in (event.primary, event.secondary)
                        ],
                        "snapshot_job_id": snapshot.get("job_id"),
                        "snapshot_created_at": snapshot.get("created_at"),
                        "object_ids": [event.primary.id, event.secondary.id],
                        "tca_utc": event.physics_result.tca.value,
                    },
                    "applied_covariance_scale": covariance_scale,
                    "applied_hbr_scale": hbr_scale,
                    "hbr_km": assessment.hbr_km,
                    "tle_age_days": assessment.provenance.get("object_metadata"),
                    "physics_calculator": assessment.method_name,
                    "physics_calculator_version": assessment.method_version,
                    "configuration_version": assessment.provenance.get("prior_model_version"),
                    "generated_research_pc": assessment.estimated_pc_scientific,
                    "generated_pc_log10": target_log10_pc,
                    "generated_risk_class": assessment.risk_assessment.physics_risk_class,
                    "features": feature_values,
                })
    parent_ids = sorted({item["parent_event_id"] for item in scenarios})
    if len(parent_ids) < 6:
        raise ValueError(f"At least six independent parent events are required for grouped evaluation; found {len(parent_ids)}")
    summary = {
        "dataset_version": SCENARIO_DATASET_VERSION,
        "snapshot_job_id": snapshot.get("job_id"),
        "snapshot_created_at": snapshot.get("created_at"),
        "snapshot_path": snapshot_path.name,
        "snapshot_sha256": _sha256(snapshot_path),
        "source_policy": "valid live, non-synthetic CelesTrak GP/TLE screening events only",
        "valid_parent_events_in_snapshot": len(events),
        "independent_parent_events_with_scenarios": len(parent_ids),
        "scenario_count": len(scenarios),
        "covariance_scales": list(COVARIANCE_SCALES),
        "hbr_scales": list(HBR_SCALES),
        "rejected_scenarios_by_reason": rejected,
        "feature_schema_version": FEATURE_SCHEMA_VERSION,
        "feature_names": list(FEATURE_NAMES),
        "physics_calculator_version": METHOD_VERSION,
        "risk_policy_version": ORION_RISK_POLICY_VERSION,
    }
    return summary, scenarios


def grouped_split(parent_event_ids: list[str], seed: int = SEED) -> dict[str, list[str]]:
    unique = sorted(set(parent_event_ids))
    if len(unique) < 6:
        raise ValueError("Grouped 70/15/15 evaluation requires at least six parent events")
    random.Random(seed).shuffle(unique)
    train_end = int(0.70 * len(unique))
    validation_end = train_end + int(0.15 * len(unique))
    splits = {
        "train": sorted(unique[:train_end]),
        "validation": sorted(unique[train_end:validation_end]),
        "test": sorted(unique[validation_end:]),
    }
    if not all(splits.values()):
        raise ValueError("Grouped split produced an empty partition")
    if any(set(splits[left]) & set(splits[right]) for left, right in (("train", "validation"), ("train", "test"), ("validation", "test"))):
        raise AssertionError("Parent event leaked across partitions")
    return splits


def _partition_indices(scenarios: list[dict[str, Any]], parent_splits: dict[str, list[str]]) -> dict[str, np.ndarray]:
    split_sets = {name: set(parent_ids) for name, parent_ids in parent_splits.items()}
    return {
        name: np.asarray([i for i, scenario in enumerate(scenarios) if scenario["parent_event_id"] in parent_ids], dtype=int)
        for name, parent_ids in split_sets.items()
    }


def _classification_metrics(y_true, y_pred, split_name: str, parent_count: int) -> dict[str, Any]:
    from sklearn.metrics import accuracy_score, confusion_matrix, f1_score, precision_recall_fscore_support

    precision, recall, f1, support = precision_recall_fscore_support(
        y_true, y_pred, labels=RISK_CLASSES, zero_division=0,
    )
    return {
        "split": split_name,
        "sample_count": int(len(y_true)),
        "parent_event_count": parent_count,
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "macro_f1": float(f1_score(y_true, y_pred, labels=RISK_CLASSES, average="macro", zero_division=0)),
        "weighted_f1": float(f1_score(y_true, y_pred, labels=RISK_CLASSES, average="weighted", zero_division=0)),
        "class_order": list(RISK_CLASSES),
        "confusion_matrix_rows_true_columns_predicted": confusion_matrix(y_true, y_pred, labels=RISK_CLASSES).tolist(),
        "per_class": {
            label: {"precision": float(precision[i]), "recall": float(recall[i]), "f1": float(f1[i]), "support": int(support[i])}
            for i, label in enumerate(RISK_CLASSES)
        },
        "class_balance": {label: int(np.sum(np.asarray(y_true) == label)) for label in RISK_CLASSES},
    }


def train_models(snapshot_path: Path = SNAPSHOT_PATH) -> dict[str, Any]:
    from joblib import dump
    from sklearn.dummy import DummyClassifier, DummyRegressor
    from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
    from sklearn.impute import SimpleImputer
    from sklearn.metrics import mean_absolute_error, mean_squared_error
    from sklearn.pipeline import Pipeline

    summary, scenarios = generate_scenarios(snapshot_path)
    parent_splits = grouped_split([item["parent_event_id"] for item in scenarios])
    index_splits = _partition_indices(scenarios, parent_splits)
    X = np.asarray([[scenario["features"][name] for name in FEATURE_NAMES] for scenario in scenarios], dtype=np.float64)
    y_pc = np.asarray([scenario["generated_pc_log10"] for scenario in scenarios], dtype=np.float64)
    y_class = np.asarray([scenario["generated_risk_class"] for scenario in scenarios], dtype=object)
    split_counts = {name: {"scenario_count": int(len(index)), "parent_event_count": len(parent_splits[name])}
                    for name, index in index_splits.items()}
    for partition in index_splits.values():
        if not len(partition):
            raise ValueError("Scenario split produced an empty partition")

    pc_model = Pipeline([
        ("imputer", SimpleImputer(strategy="median", keep_empty_features=True)),
        ("random_forest", RandomForestRegressor(
            n_estimators=300, max_depth=12, min_samples_leaf=2,
            random_state=SEED, n_jobs=1,
        )),
    ])
    pc_model.fit(X[index_splits["train"]], y_pc[index_splits["train"]])
    pc_baseline = DummyRegressor(strategy="median").fit(X[index_splits["train"]], y_pc[index_splits["train"]])

    pc_metrics = {}
    for split_name in ("validation", "test"):
        indexes = index_splits[split_name]
        truth = y_pc[indexes]
        predictions = pc_model.predict(X[indexes])
        baseline = pc_baseline.predict(X[indexes])
        pc_metrics[split_name] = {
            "sample_count": int(len(indexes)),
            "parent_event_count": len(parent_splits[split_name]),
            "mae_log10_pc": float(mean_absolute_error(truth, predictions)),
            "rmse_log10_pc": float(mean_squared_error(truth, predictions) ** 0.5),
            "baseline_median_mae_log10_pc": float(mean_absolute_error(truth, baseline)),
            "baseline_median_rmse_log10_pc": float(mean_squared_error(truth, baseline) ** 0.5),
        }

    classifier = Pipeline([
        ("imputer", SimpleImputer(strategy="median", keep_empty_features=True)),
        ("random_forest", RandomForestClassifier(
            n_estimators=300, max_depth=12, min_samples_leaf=2,
            class_weight="balanced_subsample", random_state=SEED, n_jobs=1,
        )),
    ])
    classifier.fit(X[index_splits["train"]], y_class[index_splits["train"]])
    classifier_baseline = DummyClassifier(strategy="most_frequent").fit(X[index_splits["train"]], y_class[index_splits["train"]])
    classifier_metrics = {}
    training_majority_class = str(classifier_baseline.classes_[int(np.argmax(classifier_baseline.class_prior_))])
    for split_name in ("validation", "test"):
        indexes = index_splits[split_name]
        truth = y_class[indexes]
        classifier_metrics[split_name] = _classification_metrics(
            truth, classifier.predict(X[indexes]), split_name, len(parent_splits[split_name]),
        )
        baseline_metrics = _classification_metrics(
            truth, classifier_baseline.predict(X[indexes]), split_name, len(parent_splits[split_name]),
        )
        baseline_metrics["strategy"] = "training-split majority class"
        baseline_metrics["training_majority_class"] = training_majority_class
        classifier_metrics[split_name]["majority_baseline"] = baseline_metrics
    class_balance = {label: int(np.sum(y_class == label)) for label in RISK_CLASSES}

    DATASET_PATH.parent.mkdir(parents=True, exist_ok=True)
    with DATASET_PATH.open("w", encoding="utf-8", newline="\n") as stream:
        for scenario in scenarios:
            stream.write(json.dumps(scenario, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n")
    split_manifest = {
        "version": SCENARIO_DATASET_VERSION,
        "seed": SEED,
        "grouping_key": "parent_event_id",
        "split_strategy": "fixed-seed shuffled unique parent IDs; approximately 70/15/15",
        "parent_event_ids": parent_splits,
        "scenario_counts": split_counts,
    }
    SPLIT_PATH.write_text(json.dumps(split_manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    dataset_sha256 = _sha256(DATASET_PATH)
    split_manifest_sha256 = _sha256(SPLIT_PATH)

    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    pc_bundle = {"estimator": pc_model, "feature_names": FEATURE_NAMES, "feature_schema_version": FEATURE_SCHEMA_VERSION}
    risk_bundle = {"estimator": classifier, "feature_names": FEATURE_NAMES, "feature_schema_version": FEATURE_SCHEMA_VERSION}
    dump(pc_bundle, PC_ARTIFACT, compress=3)
    dump(risk_bundle, RISK_ARTIFACT, compress=3)
    training_common = {
        "model_version": MODEL_VERSION,
        "dataset_version": SCENARIO_DATASET_VERSION,
        "scenario_dataset_filename": DATASET_PATH.name,
        "scenario_dataset_sha256": dataset_sha256,
        "split_manifest_filename": SPLIT_PATH.name,
        "split_manifest_sha256": split_manifest_sha256,
        "dataset_provenance": summary,
        "scenario_split": split_manifest,
        "features": [{"name": name, "units": FEATURE_UNITS[name]} for name in FEATURE_NAMES],
        "feature_names": list(FEATURE_NAMES),
        "feature_schema_version": FEATURE_SCHEMA_VERSION,
        "preprocessing": "scikit-learn Pipeline with median SimpleImputer fitted on training partition only; no live inference imputation when a required feature is missing",
        "random_seed": SEED,
        "grouping_strategy": "parent_event_id; all covariance/HBR variants from an event remain in one partition",
        "split_counts": split_counts,
        "independent_parent_event_counts": {name: len(ids) for name, ids in parent_splits.items()},
        "scenario_count_by_split": {name: counts["scenario_count"] for name, counts in split_counts.items()},
        "class_balance_all_scenarios": class_balance,
        "limitations": [
            "Targets are generated by ORION's own research Pc and risk policy, not observed collision outcomes.",
            "The model is a surrogate for the declared assumptions; it is not an independently validated collision predictor.",
            "A saved screening snapshot provides limited independent parent events; variants do not increase the independent-event count.",
        ],
    }
    pc_meta = {
        **training_common,
        "model_name": "ORION Research Pc Surrogate",
        "model_task": "regression",
        "target_definition": PC_TARGET_DEFINITION,
        "artifact_filename": PC_ARTIFACT.name,
        "artifact_sha256": _sha256(PC_ARTIFACT),
        "metrics": pc_metrics,
        "baseline": "training-split median log10(Pc)",
    }
    risk_meta = {
        **training_common,
        "model_name": "ORION Physics Pc Risk Classifier",
        "model_task": "three-class classification",
        "target_definition": RISK_TARGET_DEFINITION,
        "artifact_filename": RISK_ARTIFACT.name,
        "artifact_sha256": _sha256(RISK_ARTIFACT),
        "metrics": classifier_metrics,
        "baseline": "training-split majority class",
        "class_order": list(RISK_CLASSES),
        "risk_policy_version": ORION_RISK_POLICY_VERSION,
    }
    PC_METADATA.write_text(json.dumps(pc_meta, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    RISK_METADATA.write_text(json.dumps(risk_meta, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return {
        "dataset": summary,
        "split_counts": split_counts,
        "pc_regressor": {"model_name": pc_meta["model_name"], "version": MODEL_VERSION, "metrics": pc_metrics},
        "risk_classifier": {"model_name": risk_meta["model_name"], "version": MODEL_VERSION, "metrics": classifier_metrics},
        "artifacts": {"pc": PC_ARTIFACT.name, "risk": RISK_ARTIFACT.name},
    }


def math_isfinite(value: float) -> bool:
    return bool(np.isfinite(value))


def main() -> None:
    print(json.dumps(train_models(), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
